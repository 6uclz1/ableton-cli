def _load_snapshot(path: str, *, source_name: str) -> dict[str, object]:
    snapshot_path = Path(path)
    try:
        raw = snapshot_path.read_text(encoding="utf-8")
    except OSError as exc:
        raise invalid_argument(
            message=f"{source_name} file could not be read: {snapshot_path}",
            hint=f"Provide a readable UTF-8 JSON file for {source_name}.",
        ) from exc
    try:
        payload = json.loads(raw)
    except json.JSONDecodeError as exc:
        raise invalid_argument(
            message=f"{source_name} file must be valid JSON: {exc.msg}",
            hint=f"Fix JSON syntax in {snapshot_path}.",
        ) from exc
    if not isinstance(payload, dict):
        raise invalid_argument(
            message=f"{source_name} snapshot root must be an object",
            hint="Use object JSON snapshots generated by session snapshot.",
        )
    return payload


def _session_diff_result(*, from_path: str, to_path: str) -> dict[str, object]:
    from_snapshot = _load_snapshot(from_path, source_name="--from")
    to_snapshot = _load_snapshot(to_path, source_name="--to")
    result = compute_session_diff(from_snapshot, to_snapshot)
    return {
        "from_path": str(Path(from_path)),
        "to_path": str(Path(to_path)),
        **result,
    }


@session_app.command("diff")
def session_diff(
    ctx: typer.Context,
    from_path: str = typer.Option(..., "--from"),
    to_path: str = typer.Option(..., "--to"),
) -> None:  # noqa: E501
    run_client_command(
        ctx,
        command_name="session diff",
        args={"from": from_path, "to": to_path},
        fn=lambda _client: _session_diff_result(from_path=from_path, to_path=to_path),
    )


@session_app.command("capture")
def session_capture(
    ctx: typer.Context,
    track_index: Annotated[
        int, typer.Option("--track-index", help="Audio track index (0-based) to capture into")
    ],
    slot: Annotated[
        int, typer.Option("--slot", help="Empty session clip slot index (0-based) to record into")
    ],
    bars: Annotated[float, typer.Option("--bars", help="Number of bars to capture")],
    start: Annotated[
        float, typer.Option("--start", help="Transport start position in beats")
    ] = 0.0,
    set_routing: Annotated[
        bool,
        typer.Option(
            "--set-routing", help="Set the track's input routing to Resampling automatically"
        ),
    ] = False,
    analyze: Annotated[
        bool, typer.Option("--analyze", help="Run loudness/spectrum analysis on the captured file")
    ] = False,
    qa_project: Annotated[
        str | None,
        typer.Option("--qa-project", help="Run remix mastering QA against this project file"),
    ] = None,
) -> None:
    def _run() -> dict[str, object]:
        valid_track = require_track_index(track_index)
        valid_slot = require_track_index(slot, hint="Use a valid clip slot index.")
        valid_bars = require_positive_float("bars", bars, hint="Use a positive --bars value.")
        valid_start = require_non_negative_float(
            "start", start, hint="Use a non-negative --start value in beats."
        )
        return capture_session(
            get_client(ctx),
            track=valid_track,
            slot=valid_slot,
            bars=valid_bars,
            start=valid_start,
            set_routing=set_routing,
            analyze=analyze,
            qa_project=qa_project,
        )

    execute_command(
        ctx,
        command="session capture",
        args={
            "track_index": track_index,
            "slot": slot,
            "bars": bars,
            "start": start,
            "set_routing": set_routing,
            "analyze": analyze,
            "qa_project": qa_project,
        },
        action=_run,
    )


def _validate_watch_interval(interval_ms: int) -> None:
    if interval_ms < 50:
        raise invalid_argument(
            message=f"interval_ms must be >= 50, got {interval_ms}",
            hint="Use --interval-ms >= 50.",
        )


def _validate_watch_scope(scope: str) -> None:
    if scope not in WATCH_SCOPES:
        raise invalid_argument(
            message=f"scope must be one of {sorted(WATCH_SCOPES)}, got {scope!r}",
            hint="Use --scope song|tracks|transport|all.",
        )


@session_app.command("watch")
def session_watch(
    ctx: typer.Context,
    interval_ms: Annotated[
        int, typer.Option("--interval-ms", help="Poll interval in milliseconds (min 50)")
    ] = 500,
    scope: Annotated[str, typer.Option("--scope", help="song|tracks|transport|all")] = "all",
    count: Annotated[
        int | None,
        typer.Option("--count", help="Stop after N emitted diffs (unlimited if omitted)"),
    ] = None,
    include_position: Annotated[
        bool,
        typer.Option(
            "--include-position/--no-include-position",
            help="Include volatile playback position fields in diffs",
        ),
    ] = False,
) -> None:
    args = {
        "interval_ms": interval_ms,
        "scope": scope,
        "count": count,
        "include_position": include_position,
    }

    def _validate() -> dict[str, object]:
        _validate_watch_interval(interval_ms)
        _validate_watch_scope(scope)
        return {}

    if interval_ms < 50 or scope not in WATCH_SCOPES:
        execute_command(ctx, command="session watch", args=args, action=_validate)
        return

    runtime = get_runtime(ctx)
    if (
        runtime.plan
        or runtime.dry_run
        or (runtime.require_confirmation and not runtime.confirm_destructive)
    ):
        execute_command(ctx, command="session watch", args=args, action=lambda: {})
        return

    client = get_client(ctx)

    def _emit(payload: dict[str, object]) -> None:
        typer.echo(json.dumps(payload))

    try:
        run_watch_loop(
            client,
            scope=scope,
            interval_seconds=interval_ms / 1000.0,
            count=count,
            include_position=include_position,
            emit=_emit,
        )
    except KeyboardInterrupt:
        raise typer.Exit(code=0) from None


KNOWN_EVENTS: tuple[str, ...] = (
    "tempo",
    "is_playing",
    "playing_position",
    "selected_track",
)


def _validate_events(events: str | None) -> list[str]:
    if events is None:
        return []
    names = [item.strip() for item in events.split(",") if item.strip()]
    unknown = [name for name in names if name not in KNOWN_EVENTS]
    if unknown:
        raise invalid_argument(
            message=f"unknown events: {sorted(unknown)}",
            hint=f"Use --events with any of: {', '.join(KNOWN_EVENTS)}.",
        )
    return names


def _open_event_stream(ctx: typer.Context, **kwargs: object) -> EventStream:
    """Seam for tests: a stream over the resolved runtime settings."""
    return EventStream(get_runtime(ctx).settings, **kwargs)  # type: ignore[arg-type]


@session_app.command("events")
def session_events(
    ctx: typer.Context,
    events: Annotated[
        str | None,
        typer.Option("--events", help=f"Comma-separated subset of: {', '.join(KNOWN_EVENTS)}"),
    ] = None,
    count: Annotated[
        int | None,
        typer.Option("--count", help="Stop after N events (unlimited if omitted)"),
    ] = None,
    idle_timeout_ms: Annotated[
        int | None,
        typer.Option("--idle-timeout-ms", help="Stop after this long with no event"),
    ] = None,
) -> None:
    """Stream events pushed by Live instead of polling for diffs."""
    args = {"events": events, "count": count, "idle_timeout_ms": idle_timeout_ms}

    def _validate() -> dict[str, object]:
        _validate_events(events)
        return {}

    runtime = get_runtime(ctx)
    if (
        runtime.plan
        or runtime.dry_run
        or (runtime.require_confirmation and not runtime.confirm_destructive)
    ):
        execute_command(ctx, command="session events", args=args, action=_validate)
        return

    if events is not None and any(
        name.strip() and name.strip() not in KNOWN_EVENTS for name in events.split(",")
    ):
        execute_command(ctx, command="session events", args=args, action=_validate)
        return

    selected = _validate_events(events)
    stream = _open_event_stream(ctx, events=selected, idle_timeout_ms=idle_timeout_ms)
    try:
        stream.open()
        for event in stream.events(count=count):
            typer.echo(json.dumps(event))
    except KeyboardInterrupt:
        raise typer.Exit(code=0) from None
    finally:
        stream.close()


